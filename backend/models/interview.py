"""
models/interview.py — Pydantic models for the interview flow.
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Optional
from pydantic import BaseModel, Field


class AnswerSource(str, Enum):
    voice = "voice"
    text  = "text"
    auto  = "auto"   # inferred from previously given info


class AnswerConfidence(str, Enum):
    high   = "high"
    medium = "medium"
    low    = "low"


# ── Interview Q&A models ──────────────────────────────────────────────────────

class InterviewQuestion(BaseModel):
    """A question to ask the user during the interview."""
    question_id: str
    question_text: str          # Natural language question generated by Gemma
    hint: Optional[str] = None  # Optional hint/example from form description
    options: Optional[list[str]] = None   # Pre-filled if it's a choice question
    field_type: str = "short_text"
    required: bool = False
    already_answered: bool = False


class AnswerSubmission(BaseModel):
    """Payload sent by the UI when the user submits an answer."""
    question_id: str
    raw_answer: str             # Raw text from user (voice transcript or typed)


class StoredAnswer(BaseModel):
    """Validated answer stored in the interview state."""
    question_id: str
    raw_answer: str
    interpreted_value: Any      # The structured value after Gemma interpretation
    source: AnswerSource = AnswerSource.text
    confidence: AnswerConfidence = AnswerConfidence.high
    validated: bool = False
    validation_error: Optional[str] = None


class InterviewStatus(BaseModel):
    """Current progress of the interview session."""
    total_questions: int
    answered: int
    required_remaining: int
    optional_remaining: int
    is_complete: bool
    completion_percent: float
    current_question: Optional[InterviewQuestion] = None


# ── Autofill models ───────────────────────────────────────────────────────────

class AutofillEntry(BaseModel):
    """Single field entry for autofill."""
    value: Any
    type: str        # FieldType value (short_text, radio, checkbox, etc.)
    index: int       # 0-based question index for DOM targeting
    question_id: str


class AutofillData(BaseModel):
    """Answer map returned to the Chrome extension for autofilling."""
    answers: dict[str, AutofillEntry] = Field(default_factory=dict)
    form_title: Optional[str] = None
    total_fields: int = 0
    filled_count: int = 0


# ── Edit request ──────────────────────────────────────────────────────────────

class EditRequest(BaseModel):
    """Request to edit a previously given answer."""
    question_id: str
    new_answer: str
